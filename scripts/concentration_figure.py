"""Writes the paper's cost-concentration figure (pgfplots) from a reader run.

Run from the CDD root:

    python scripts/concentration_figure.py RUN FIELD [FRESH_RUN] \\
        > paper/figures/concentration.tex

FIELD is the attribution column of errors.jsonl: ``shapley`` (Shapley values, which sum to each
stream's R_interp) or ``delta_c`` (single repairs). Readers with at least 30 errors are drawn.
With FRESH_RUN, each reader gets a second curve from that run: RUN's curves solid, FRESH_RUN's
dashed, in the same colour and marker, and the legend gives both error counts.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from paper_numbers import errors

run, field = Path("runs") / sys.argv[1], sys.argv[2]
fresh = Path("runs") / sys.argv[3] if len(sys.argv) > 3 else None
LABEL = {"shapley": "Shapley value", "delta_c": r"$\Delta C$"}[field]
# (condition, legend, colour, line style without FRESH_RUN, marker), in legend order.
CURVES = [
    ("qwen-json", "Qwen, free JSON", "seriesB", "dashed", "square*"),
    ("regex", "Regex", "seriesA", "solid", "*"),
    ("laya-atomic", "Laya, zero-shot", "seriesC", "densely dotted", "triangle*"),
]
sources = f"runs/{run.name}/errors.jsonl" + (
    f" and runs/{fresh.name}/errors.jsonl" if fresh else ""
)
styles = (
    "each run has its own line style (solid, dashed) and each reader its own marker"
    if fresh
    else "each curve also has its own line style and marker"
)

print(f"""% Figure: cost concentration of reading errors (generated by
% CDD/scripts/concentration_figure.py from {sources}, field {field};
% readers with at least 30 errors).
% Colours: categorical slots 1-3 of the validated default palette; {styles},
% so the figure reads in greyscale.
\\definecolor{{seriesA}}{{HTML}}{{2A78D6}}
\\definecolor{{seriesB}}{{HTML}}{{EB6834}}
\\definecolor{{seriesC}}{{HTML}}{{1BAF7A}}
\\begin{{tikzpicture}}
\\begin{{axis}}[
  width=0.82\\linewidth, height=5.2cm,
  xmin=0, xmax=50, ymin=0, ymax=102,
  xtick={{0,10,20,30,40,50}}, ytick={{0,20,40,60,80,100}},
  xlabel={{Share of the reader's errors, costliest first (\\%)}},
  ylabel={{Share of positive {LABEL} (\\%)}},
  label style={{font=\\small}}, tick label style={{font=\\footnotesize}},
  grid=major, major grid style={{black!12, line width=0.3pt}},
  axis line style={{black!45}}, tick style={{black!45}},
  legend style={{font=\\footnotesize, draw=none, fill=white, fill opacity=0.85,
    text opacity=1, at={{(0.98,0.04)}}, anchor=south east, cells={{anchor=west}}}},
  legend cell align=left,
]""")


def curve(source: Path, key: str) -> list[str]:
    """Cumulative share of positive cost against share of errors, costliest first."""
    costs = sorted(
        (float(e[field] or 0) for e in errors(source) if e["condition"] == key), reverse=True
    )
    if len(costs) < 30:
        return []
    positive = sum(c for c in costs if c > 0)
    points, running = ["(0.0,0.0)"], 0.0
    for i, c in enumerate(costs, start=1):
        running += max(0.0, c)
        points.append(f"({100 * i / len(costs):.1f},{100 * running / positive:.1f})")
    return points


for key, legend, colour, style, mark in CURVES:
    points = curve(run, key)
    if not points:
        continue
    second = curve(fresh, key) if fresh else []
    print(f"\\addplot[{colour}, {'solid' if fresh else style}, line width=1.2pt, mark={mark},")
    print(f"  mark size=1.6pt, mark repeat=3, mark phase=2] coordinates {{{' '.join(points)}}};")
    counts = f"{len(points) - 1} and {len(second) - 1}" if second else f"{len(points) - 1}"
    print(f"\\addlegendentry{{{legend} ({counts} errors)}}")
    if second:
        repeat = max(3, (len(second) - 1) // 18)
        print(f"\\addplot[{colour}, dashed, line width=1.2pt, mark={mark}, mark size=1.6pt,")
        print(f"  mark repeat={repeat}, mark phase=2, forget plot]")
        print(f"  coordinates {{{' '.join(second)}}};")
print(r"""\draw[black!35, densely dashed, line width=0.5pt] (axis cs:10,0) -- (axis cs:10,102);
\node[font=\footnotesize, text=black!60, anchor=south east] at (axis cs:9.6,2) {top 10\%};
\end{axis}
\end{tikzpicture}""")
