"""Writes the paper's figure of each error's price under two decisions (pgfplots).

Run from the CDD root:

    python scripts/error_price_figure.py READER_RUN PROMISING_RUN \\
        > paper/figures/error-prices.tex

Plots every error of READER_RUN by its single-repair effect (``delta_c``) under replenishment
(x) and under the promising run (y), joined on (stream, condition, error_id). Both axes use a
signed log scale, sign(v) log10(1 + |v|), so errors worth 100,000 and errors worth 10 show on one
plot. An error is costly in a decision when its repair saves cost there (delta_c > 0).
"""

import json
import math
import sys
from pathlib import Path

reader_run, promising_run = Path("runs") / sys.argv[1], Path("runs") / sys.argv[2]


def by_error(run: Path) -> dict[tuple[str, str, str], float]:
    rows = (json.loads(line) for line in (run / "errors.jsonl").read_text().splitlines() if line)
    return {(e["stream"], e["condition"], e["error_id"]): float(e["delta_c"] or 0) for e in rows}


def symlog(v: float) -> float:
    return math.copysign(math.log10(1 + abs(v)), v)


def ticks(values: list[int]) -> tuple[str, str]:
    labels = {100: "100", 1000: "1k", 10000: "10k", 100000: "100k"}
    positions = ",".join(f"{symlog(v):.3f}" for v in values)
    names = ",".join("0" if v == 0 else ("$-$" if v < 0 else "") + labels[abs(v)] for v in values)
    return positions, names


replenishment, promising = by_error(reader_run), by_error(promising_run)
keys = sorted(replenishment.keys() & promising.keys())
EPS = 1e-6
# (class, colour, marker, size, legend); errors costly in neither decision are drawn first, in grey.
CLASSES = [
    ("neither", "black!45", "*", "1.2pt", None),
    ("replenishment", "seriesA", "*", "1.5pt", "Replenishment only"),
    ("both", "seriesB", "square*", "2.0pt", "Both decisions"),
    ("promising", "seriesC", "triangle*", "2.4pt", "Promising only"),
]


def kind(x: float, y: float) -> str:
    if x > EPS and y > EPS:
        return "both"
    if x > EPS:
        return "replenishment"
    if y > EPS:
        return "promising"
    return "neither"


points: dict[str, list[str]] = {name: [] for name, *_ in CLASSES}
for key in keys:
    x, y = replenishment[key], promising[key]
    points[kind(x, y)].append(f"({symlog(x):.3f},{symlog(y):.3f})")

xt, xl = ticks([-10000, -100, 0, 100, 10000, 100000])
yt, yl = ticks([-100, 0, 100, 1000])
print(f"""% Figure: each error's single-repair effect under two decisions (generated by
% CDD/scripts/error_price_figure.py from runs/{reader_run.name} and runs/{promising_run.name};
% {len(keys)} errors, signed log scales). Colours: categorical slots 1-3 of the validated default
% palette, each with its own marker, so the figure reads in greyscale.
\\definecolor{{seriesA}}{{HTML}}{{2A78D6}}
\\definecolor{{seriesB}}{{HTML}}{{EB6834}}
\\definecolor{{seriesC}}{{HTML}}{{1BAF7A}}
\\begin{{tikzpicture}}
\\begin{{axis}}[
  width=0.82\\linewidth, height=5.2cm,
  xmin={symlog(-20000):.2f}, xmax={symlog(200000):.2f},
  ymin={symlog(-400):.2f}, ymax={symlog(3000):.2f},
  xtick={{{xt}}}, xticklabels={{{xl}}},
  ytick={{{yt}}}, yticklabels={{{yl}}},
  xlabel={{Single-repair effect, replenishment}},
  ylabel={{Effect, surge promising}},
  label style={{font=\\small}}, tick label style={{font=\\footnotesize}},
  grid=major, major grid style={{black!12, line width=0.3pt}},
  axis line style={{black!45}}, tick style={{black!45}},
  legend style={{font=\\footnotesize, draw=none, fill=white, fill opacity=0.85,
    text opacity=1, at={{(0.5,1.03)}}, anchor=south, legend columns=3,
    /tikz/every even column/.append style={{column sep=0.6em}}}},
  legend cell align=left,
  legend image post style={{draw opacity=1, fill opacity=1}},
]""")
for name, colour, mark, size, legend in CLASSES:
    if not points[name]:
        continue
    forget = "" if legend else ", forget plot"
    print(f"\\addplot[only marks, mark={mark}, mark size={size}, draw={colour}, fill={colour},")
    # The two crowded classes are half transparent, so errors that share a point show darker.
    opacity = "0.5" if name in ("neither", "replenishment") else "0.9"
    style = f"draw opacity={opacity}, fill opacity={opacity}{forget}"
    print(f"  {style}] coordinates {{{' '.join(points[name])}}};")
    if legend:
        print(f"\\addlegendentry{{{legend} ({len(points[name])})}}")
print(r"""\end{axis}
\end{tikzpicture}""")
